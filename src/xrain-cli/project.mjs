import { appendFile, mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, basename } from 'node:path';
import { CliError, randomId, sha256 } from './core.mjs';
import { assembleProject } from './project-source.mjs';
import { buildAppArtifact } from './app.mjs';
import { projectFunctionCommands } from './project-function.mjs';

const json = value => JSON.stringify(value, null, 2) + '\n';
function receipt(metadata) {
  const { inputs, git, ...summary } = metadata;
  const { uncommittedInputs, ...gitSummary } = git;
  return { ...summary, inputCount: inputs.length, git: { ...gitSummary,
    ...(uncommittedInputs ? { uncommittedInputCount: uncommittedInputs.length } : {}) } };
}
async function writeNew(path, bytes) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, bytes, { flag: 'wx' });
}

export async function initProject(ctx) {
  const namespace = ctx.args.required('namespace'), label = ctx.args.required('label').trim();
  if (!/^[a-z][a-z0-9]{1,15}$/.test(namespace) || namespace.endsWith('\n')) throw new CliError('Namespace must have 2-16 lowercase letters or digits and start with a letter.');
  if (!label.length || label.length > 256) throw new CliError('Label must have 1-256 characters.');
  const root = resolve(ctx.args.value('dir') ?? namespace), path = join(root, 'xrain-project.json');
  const descriptor = { schemaVersion: 1, package: { packageId: randomId('apg'), namespace, label,
    baseVersion: '1.0.0', releaseVersionId: randomId('apv') }, records: [], tenantFunctions: [] };
  await writeNew(path, json(descriptor));
  const ignore = join(root, '.gitignore');
  let previous = '';
  try { previous = await readFile(ignore, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const missing = ['/.artifacts/', '/.local/'].filter(line => !previous.split(/\r?\n/).includes(line));
  if (missing.length) await appendFile(ignore, (previous && !previous.endsWith('\n') ? '\n' : '') + missing.join('\n') + '\n');
  await mkdir(join(root, 'platform/metadata'), { recursive: true });
  const readme = `# ${label}\n\nMaintain platform resources in platform/metadata/, functions in platform/functions/, and orchestration versions in platform/orchestrations/.\nDeclare every package record and separately delivered tenant function in xrain-project.json. No business resources are generated by init.\n\nUse agents/ for agent definitions and deliverable workspace files, backend/ for business services, clients/web|desktop|android|ios|miniprogram/ for owned clients, and shared/ for shared code. Create these directories only when needed.\nUse data/seeds/ for explicitly delivered initial records, data/samples/ for synthetic examples, and data/import-templates/ for empty templates. Real business data and runtime state stay in their systems.\n\nRun xrain-cli project assemble --project . to assemble offline, or xrain-cli project build --project . --profile NAME to build a new candidate using the platform. Both return exact output paths.\nModule scripts require an exact project esbuild dependency and its package-manager lockfile. Install these with your project package manager; the CLI does not install dependencies.\n\n.artifacts/ contains ignored outputs and input snapshots; .local/ contains ignored local settings. Build does not import, install, select a function version, publish or deploy.\n`;
  try { await writeNew(join(root, 'README.md'), readme); } catch (error) { if (error.code !== 'EEXIST') throw error; }
  ctx.reporter.print({ project: root, descriptor: path, packageId: descriptor.package.packageId });
  return 0;
}

export async function saveAssembly(assembly) {
  const { root, source, tenantFunctions, inputs } = assembly;
  const base = join(root, '.artifacts/appkg');
  await mkdir(base, { recursive: true });
  // A separate attempt directory also permits repeated release builds while
  // retaining the same formal identity and every previously built original.
  const directory = await mkdtemp(join(base, source.versionId + '-'));
  const sourcePath = join(directory, 'source.json'), sourceBytes = json(source);
  await writeNew(sourcePath, sourceBytes);
  for (const [file, bytes] of inputs.files) await writeNew(join(directory, 'inputs', file), bytes);
  const functions = [];
  for (const [index, definition] of tenantFunctions.entries()) {
    const output = join(root, '.artifacts/functions', basename(directory), `function-${index + 1}.json`);
    await writeNew(output, json(definition));
    functions.push({ key: definition.key, output, sha256: sha256(json(definition)) });
  }
  const metadata = { schemaVersion: 1, status: 'assembled', mode: assembly.release ? 'release' : 'candidate',
    packageId: source.packageId, versionId: source.versionId, version: source.version,
    source: sourcePath, sourceSha256: sha256(sourceBytes), functions,
    inputs: inputs.list(), git: assembly.git, compiler: assembly.compiler };
  const assemblyPath = join(directory, 'assembly.json');
  await writeNew(assemblyPath, json(metadata));
  return { directory, metadata, assemblyPath };
}

export async function projectCommands(ctx) {
  if (ctx.args.command(1) === 'function') return projectFunctionCommands(ctx);
  if (ctx.args.command(1) === 'init') return initProject(ctx);
  const assembly = await assembleProject(ctx.args.value('project') ?? '.', { release: ctx.args.has('release') });
  const saved = await saveAssembly(assembly);
  if (ctx.args.command(1) === 'assemble') {
    ctx.reporter.print(receipt({ ...saved.metadata, metadata: saved.assemblyPath }));
    return 0;
  }
  try {
    const built = await buildAppArtifact(ctx, { sourcePath: saved.metadata.source,
      output: join(saved.directory, `${assembly.source.versionId}.appkg`), requireMetadata: true });
    const metadataPath = join(saved.directory, 'build.json');
    const result = { ...saved.metadata, ...built, status: 'built', metadata: metadataPath };
    await writeNew(metadataPath, json(result));
    ctx.reporter.print(receipt(result));
    return 0;
  } catch (error) {
    // Retain this attempt's source for diagnosis; never fall back to an older
    // archive or erase another build. A failed attempt has no success receipt.
    await writeNew(join(saved.directory, 'failure.json'), json({ status: 'failed', code: error.code ?? 'build_failed', source: saved.metadata.source }));
    if (error instanceof CliError) error.details = { ...error.details, assembly: saved.assemblyPath };
    throw error;
  }
}
