import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const outfile = join(root, 'skills/xrain-cli/scripts/xrain-cli.mjs');
const result = await build({ absWorkingDir: root, entryPoints: ['src/xrain-cli/bin.mjs'], outfile,
  bundle: true, platform: 'node', target: 'node22.12', format: 'esm', charset: 'utf8', write: false,
  legalComments: 'none', metafile: true, banner: { js: '#!/usr/bin/env node\n// Generated by npm run build. Edit src/xrain-cli/, then rebuild. See THIRD_PARTY_NOTICES.txt.' } });
for (const output of Object.values(result.metafile.outputs)) for (const item of output.imports)
  if (!item.external || !item.path.startsWith('node:')) throw new Error(`Unexpected runtime dependency: ${item.path}`);
const license = await readFile(join(root, 'node_modules/jose/LICENSE.md'), 'utf8');
const josePackage = JSON.parse(await readFile(join(root, 'node_modules/jose/package.json'), 'utf8'));
const notices = `Bundled dependency: jose ${josePackage.version}\nSource: https://github.com/panva/jose\nLicense: MIT\n\n${license.trim()}\n`;
const outputs = [[outfile, result.outputFiles[0].text], [join(root, 'skills/xrain-cli/scripts/THIRD_PARTY_NOTICES.txt'), notices]];
for (const [path, text] of outputs) {
  if (check) {
    let actual;
    try { actual = await readFile(path, 'utf8'); } catch {}
    if (actual !== text) throw new Error(`${path} is missing or stale. Run npm run build.`);
  } else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, text); }
}
console.log(`${check ? 'Verified' : 'Built'} standalone XRain CLI (${Buffer.byteLength(result.outputFiles[0].text).toLocaleString('en-US')} bytes; only Node built-in runtime imports).`);
